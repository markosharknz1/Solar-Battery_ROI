/** Spot checks: Adelaide 5000 -> zone 3, Melbourne 3000 -> zone 4, Darwin 0800 -> zone 2,
 * Alice Springs 0870 -> zone 1, Hobart 7000 -> zone 4, Brisbane 4000 -> zone 3. */
export function solarZoneForPostcode(postcode: string): { zone: SolarZone; annualKwhPerKw: number } | null {
  if (!/^\d{4}$/.test(postcode.trim())) return null
  const code = Number(postcode)
  const range = ZONE_RANGES.find(([from, to]) => code >= from && code <= to)
  if (!range) return null
  return { zone: range[2], annualKwhPerKw: ZONE_ANNUAL_KWH_PER_KW[range[2]] }
}
